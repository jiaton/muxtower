const ZERO: [number, number][] = [
  [0x0300, 0x036f],
  [0x0483, 0x0489],
  [0x0591, 0x05bd],
  [0x200b, 0x200f],
  [0x2028, 0x202e],
  [0x2060, 0x2064],
  [0x20d0, 0x20ff],
  [0xfe00, 0xfe0f],
  [0xfe20, 0xfe2f],
  [0xfeff, 0xfeff],
  [0x1f3fb, 0x1f3ff],
  [0xe0000, 0xe01ef],
]

function within(ranges: [number, number][], code: number): boolean {
  let lo = 0
  let hi = ranges.length - 1
  while (lo <= hi) {
    const mid = (lo + hi) >> 1
    if (code < ranges[mid][0]) hi = mid - 1
    else if (code > ranges[mid][1]) lo = mid + 1
    else return true
  }
  return false
}

export function cellWidth(code: number): 0 | 1 | 2 {
  if (code < 0x300) return 1
  if (within(ZERO, code)) return 0
  return within(WIDE, code) ? 2 : 1
}

/** Cells taken by a string. */
export function textCells(text: string): number {
  let cells = 0
  for (const char of text) cells += cellWidth(char.codePointAt(0)!)
  return cells
}
